"""What a real dwelling's boundary costs the solver.

Ticket 58. Every Envelope this harness has ever solved is parametric. ADR 0029
fitted the second family to real dwellings on **area, perimeter and bbox
occupancy** -- three moments -- and recorded the real-boundary arm as the option
not taken. This is that arm, and it is a **ladder** rather than a single
comparison, because a real dwelling differs from `CORPUS_ENVELOPES` in two ways
at once and they are worth separating:

| arm | Envelope | ground truth | what the step isolates |
|---|---|---|---|
| `corpus` | `CORPUS_ENVELOPES[n]` | generated by `ground_truth` | -- the control, ADR 0029's winner |
| `cap` | `envelope_approx(mask, 2)`, per dwelling | generated by `ground_truth` | **sampling**: one Envelope per real dwelling instead of one per room count, same shape family |
| `real` | the true 250 mm cell mask | the dwelling's own Rooms, **re-fitted to that mask** | **shape and arrangement**: the articulation ADR 0003 cannot express |

`corpus` -> `cap` holds the shape family fixed and moves only the sampling.
`cap` -> `real` holds the dwelling fixed and moves only the boundary.

## The witness, and why this arm's claim is weaker than Parts I-III's

Parts I-III rest on `ground_truth` being a **provable** witness: it constructs a
valid exact tiling, so a failure to solve is a fact about the projection problem
and never about an impossible Brief. **That guarantee cannot be had on a real
boundary**, and the arm had to work for the weaker one it does have.

`ground_truth` is unusable here: it gives every Envelope part at least one room,
and a real outline needs a median of **6** parts against 1-4 on both shipped
fixtures, with **96 %** of dwellings carrying a part no room fits
(`rectangularise/real_boundary.py`).

The dwelling's own converted rectangles are unusable **as recorded**: they are
fitted to the CAP Envelope, a superset of the true outline, so on the true
outline they fail two hard predicates at once -- H1 (a Room pokes into ground the
dwelling never occupied) and H3 (cells no rectangle reaches). Seven of the first
eight real slots had an invalid witness that way.

What this arm uses is therefore a **re-fit**: `rectangularise/real_envelope.py`
runs the shipped conversion with the domain set to the true mask, and the
rectangles that come back are inside the boundary by construction. They still do
not tile it exactly -- ADR 0014 caps a Room at two rectangles and the residue is
ADR 0028's enclosed void -- so the witness is **coverage-soft**, median **94 %**
of the true interior. It is a witness for the constraint set the solver actually
enforces, exact tiling being posted soft, and it is **not** the kind of witness
Parts I-III quote. A `real`-arm INFEASIBLE does not prove the solver failed.
Every number this file prints carries that caveat, and `valid_geom` /
`truth_valid_geom` exist to separate the two readings rather than blur them.

Reads `../rectangularise/series/real_envelopes.json.gz`. Config is
`fixture_delta.py`'s, verbatim, so the `corpus` column is comparable with
ADR 0029's table rather than merely similar to it.

Run:  ../../venv/Scripts/python.exe real_arm.py [seeds]
Writes results/REAL_ARM.jsonl and prints the tables.
"""

from __future__ import annotations

import gzip
import json
import pathlib
import random
import re
import sys
import time
from math import comb
from typing import Dict, List, Optional, Tuple

import scenarios
from geometry import Envelope, Rect, adjacency_matrix
from scenarios import (Brief, GRID_MM, RoomSpec, STANDARDS, assign_kinds,
                       comp_bounds, composition, envelope_for, make_brief,
                       make_proposal, mm)
from solver import SolveConfig, project
from validate import check

HERE = pathlib.Path(__file__).parent
RESULTS = HERE / "results"
RESULTS.mkdir(exist_ok=True)
OUT = RESULTS / "REAL_ARM.jsonl"
SERIES = HERE / ".." / "rectangularise" / "series" / "real_envelopes.json.gz"

scenarios.ASSIGN_TIME_LIMIT_S = 10.0
scenarios.ASSIGN_WORKERS = 4
scenarios.BRIEF_ATTEMPTS = 12

WORKERS = 4
BASE_SEED = 20260817
DOOR_MIN_ADR = mm(1.0)
T_INT_PUBLISHED = 100
SHIPPED_LIMIT = 15.0
SHIPPED_TAU = 4
MAX_ASPECT = 4

ARMS = ("corpus", "cap", "real")
EXPOSURES = ("detached", "corpus_median")


_H3 = re.compile(r"^H3 (\d+) interior cells unassigned")


def _unassigned(v: dict) -> int:
    """Cells the validator found belonging to no Room, from its H3 message."""
    for f in v.get("failures") or []:
        m = _H3.match(str(f))
        if m:
            return int(m.group(1))
    return 0


def _ok_but_tiling(v: dict) -> bool:
    """Every hard predicate except H3's exact tiling."""
    if v.get("ok"):
        return True
    fails = v.get("failures") or []
    return bool(fails) and all(_H3.match(str(f)) for f in fails)


def _rects(spec) -> Tuple[Rect, ...]:
    return tuple(Rect(a, b, c, d) for a, b, c, d in spec)


def envelope_from(row: dict, tag: str, exposure: str) -> Envelope:
    return Envelope(
        f"{tag} n={row['n']} {row['k'][:12]}", row["W"], row["H"],
        _rects(row[f"{tag}_notches"]), _rects(row[f"{tag}_parts"]), exposure)


def brief_from_truth(name: str, env: Envelope, truth: List[Rect], seed: int,
                     door_min: int, window_min: int, clear_t: int,
                     required_frac: float = 0.30, forbidden_frac: float = 0.10):
    """`make_brief` with the ground truth SUPPLIED rather than generated.

    Every other step is `make_brief`'s, unchanged and in the same order --
    `composition`, `assign_kinds` under the same bounds, the same adjacency
    sampling at the same fractions off the same seeded `Random`. Only the source
    of `truth` differs, which is the whole of what this arm is testing.
    """
    n = len(truth)
    mix = composition(n)
    last = None
    for attempt in range(scenarios.BRIEF_ATTEMPTS):
        rng = random.Random(seed + attempt)
        kinds = assign_kinds(truth, env, door_min, window_min, seed + attempt,
                             comp_bounds(mix), clear_t)
        if kinds is None:
            last = "no valid room-type assignment"
            continue
        rooms = [RoomSpec(f"{k}{i}", k, *STANDARDS[k]) for i, k in enumerate(kinds)]
        adj_door = adjacency_matrix(truth, door_min)
        adj_any = adjacency_matrix(truth, 1)
        true_pairs = [(i, j) for i in range(n) for j in range(i + 1, n)
                      if adj_door[i][j]]
        non_pairs = [(i, j) for i in range(n) for j in range(i + 1, n)
                     if not adj_any[i][j]]
        rng.shuffle(true_pairs)
        rng.shuffle(non_pairs)
        required = sorted(true_pairs[: max(1, round(len(true_pairs) * required_frac))])
        forbidden = sorted(non_pairs[: max(1, round(len(non_pairs) * forbidden_frac))])
        return (Brief(name=name, env=env, grid_mm=GRID_MM, rooms=rooms,
                      entry=kinds.index("hall"), required_adj=required,
                      forbidden_adj=forbidden, door_min=door_min,
                      max_aspect=MAX_ASPECT), list(truth), kinds)
    raise RuntimeError(f"{name}: no Brief ({last})")


def one(row: dict, seed: int, exposure: str, arm: str) -> dict:
    n = row["n"]
    r = {"k": row["k"], "n": n, "seed": seed, "exposure": exposure, "arm": arm,
         "limit": SHIPPED_LIMIT, "tau": SHIPPED_TAU, "t_int": T_INT_PUBLISHED,
         "min_rects": row["min_rects"], "notches_all": row["notches_all"],
         "witness_cov": row["witness_cov"]}
    t0 = time.perf_counter()
    try:
        if arm == "corpus":
            env = envelope_for(n, exposure, fixture="corpus")
        else:
            env = envelope_from(row, arm, exposure)
        # `clear_t` MUST equal the solver's `t_int_mm` while `erode_minima` is
        # on -- ADR 0029 consequence 7. A truth built at 0 satisfies the minima
        # on the solved rect rather than the clear one, stops being a witness,
        # and the arm reads as a fixture defect.
        if arm == "real":
            truth = list(_rects(row["truth"]))
            brief, truth, kinds = brief_from_truth(
                f"real-{n}", env, truth, seed, DOOR_MIN_ADR,
                scenarios.WINDOW_MIN, clear_t=T_INT_PUBLISHED)
        else:
            brief, truth, kinds = make_brief(
                f"{arm}-{n}", env, n, seed, DOOR_MIN_ADR, scenarios.WINDOW_MIN,
                clear_t=T_INT_PUBLISHED)
        proposal = make_proposal(truth, kinds, seed, sigma=mm(0.5))
        wit = check(brief, list(truth))
        r["truth_valid"] = bool(wit["ok"])
        r["truth_fails"] = wit["failures"][:3] if not wit["ok"] else None
        r["truth_valid_geom"] = _ok_but_tiling(wit)
        r["truth_unassigned"] = _unassigned(wit)
        r["interior_m2"] = round(env.interior_area * (GRID_MM / 1000) ** 2, 2)
        r["perim_m"] = round(sum(hi - lo for (_, _, lo, hi, _) in env.all_faces())
                             * GRID_MM / 1000, 2)
        r["n_parts"] = len(env.parts)
        r["n_notches"] = len(env.notches)
    except Exception as e:                    # noqa: BLE001 - a result, not a bug
        r["status"] = "no_brief"
        r["error"] = str(e)[:160]
        r["gen_s"] = round(time.perf_counter() - t0, 3)
        return r
    r["gen_s"] = round(time.perf_counter() - t0, 3)

    cfg = SolveConfig(
        workers=WORKERS, time_limit_s=SHIPPED_LIMIT, seed=seed,
        fix_relations=True, relation_confidence=SHIPPED_TAU,
        soft=("coverage",), area_units="mm_affine", erode_minima=True,
        t_int_mm=T_INT_PUBLISHED,
    )
    res = project(brief, proposal, cfg)
    r["status"] = res.status
    r["wall"] = round(res.wall_time_s, 4)
    r["valid_at"] = next((round(t, 4) for t, o in res.trace
                          if o < cfg.soft_weight), None)
    r["objective"] = res.objective
    ok = False
    if res.rooms:
        v = check(brief, res.rooms)
        r["valid"] = bool(v["ok"])
        r["failures"] = v["failures"][:3] if not v["ok"] else None
        ok = bool(v["ok"]) and res.objective is not None \
            and res.objective < cfg.soft_weight
        # C6 discards a candidate with unassigned floor, and on a real outline
        # that is the normal case: a dwelling's own Rooms do not tile their own
        # boundary at ADR 0014's two-rectangle cap. This second reading keeps
        # every hard predicate EXCEPT exact tiling, so "the arrangement is
        # wrong" is separable from "floor is left over". It is a diagnostic and
        # never a survivor -- `model.no_unassigned_area` is hard at the bar.
        r["valid_geom"] = _ok_but_tiling(v)
        r["unassigned"] = _unassigned(v)
    else:
        r["valid"] = r["failures"] = r["valid_geom"] = None
        r["unassigned"] = None
    r["survivor"] = ok
    return r


def run(rows: List[dict], seeds: int) -> List[dict]:
    out: List[dict] = []
    with OUT.open("w", encoding="utf-8") as fh:
        for row in rows:
            for exposure in EXPOSURES:
                for s in range(seeds):
                    for arm in ARMS:
                        rec = one(row, BASE_SEED + s, exposure, arm)
                        out.append(rec)
                        fh.write(json.dumps(rec) + "\n")
                        fh.flush()
                        print(f"  n={rec['n']:<3} {exposure:<14} seed{s} "
                              f"{arm:<7} {rec['status']:<12} "
                              f"{'survivor' if rec.get('survivor') else '-':<9} "
                              f"{rec.get('wall', 0):.2f}s", flush=True)
    return out


def _p(v: List[float], q: float) -> Optional[float]:
    if not v:
        return None
    v = sorted(v)
    i = (len(v) - 1) * q
    lo = int(i)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] * (1 - (i - lo)) + v[hi] * (i - lo)


def mcnemar(rows: List[dict], a: str, b: str) -> None:
    """Exact two-sided McNemar on the discordant slots, ADR 0019's test.

    The slot is `(dwelling, exposure, seed)`: the `corpus` arm is that
    dwelling's room count, so all three arms answer for the same dwelling.
    """
    slots: Dict[tuple, Dict[str, bool]] = {}
    for r in rows:
        slots.setdefault((r["k"], r["exposure"], r["seed"]), {})[r["arm"]] = \
            bool(r.get("survivor"))
    both = only_a = only_b = neither = 0
    for v in slots.values():
        if a not in v or b not in v:
            continue
        x, y = v[a], v[b]
        both += x and y
        only_a += x and not y
        only_b += y and not x
        neither += not x and not y
    tot = both + only_a + only_b + neither
    d = only_a + only_b
    line = (f"  {a:>6} vs {b:<6} over {tot:>4} slots: both {both}, "
            f"only {a} {only_a}, only {b} {only_b}, neither {neither}")
    if d:
        k = min(only_a, only_b)
        pv = min(1.0, 2 * sum(comb(d, i) for i in range(k + 1)) / 2 ** d)
        print(f"{line}   exact McNemar p = {pv:.4f}")
    else:
        print(f"{line}   no discordant pairs")


def report(rows: List[dict]) -> None:
    print("\n" + "=" * 78)
    print("What each arm hands the solver")
    print(f"  {'arm':<7} {'m2':>8} {'perim m':>8} {'parts':>6} {'notches':>8} "
          f"{'m2/room':>8}")
    for arm in ARMS:
        g = [r for r in rows if r["arm"] == arm and "interior_m2" in r]
        if not g:
            continue
        print(f"  {arm:<7} {_p([r['interior_m2'] for r in g], .5):>8.1f} "
              f"{_p([r['perim_m'] for r in g], .5):>8.1f} "
              f"{_p([r['n_parts'] for r in g], .5):>6.0f} "
              f"{_p([r['n_notches'] for r in g], .5):>8.0f} "
              f"{_p([r['interior_m2'] / r['n'] for r in g], .5):>8.2f}")

    print("\n" + "=" * 78)
    print("Survivor rate, time to VALID, and where each arm loses")
    for arm in ARMS:
        g = [r for r in rows if r["arm"] == arm]
        sv = [r for r in g if r.get("survivor")]
        t = [r["valid_at"] for r in sv if r.get("valid_at") is not None]
        nb = [r for r in g if r["status"] == "no_brief"]
        inf = [r for r in g if r["status"] == "INFEASIBLE"]
        unk = [r for r in g if r["status"] == "UNKNOWN"]
        tv = [r for r in g if r.get("truth_valid") is False]
        print(f"  {arm:<7} survivors {len(sv):>4}/{len(g):<4} "
              f"({100 * len(sv) / max(len(g), 1):5.1f} %)  "
              f"t-to-VALID p50 {(_p(t, .5) or 0):.2f} p90 {(_p(t, .9) or 0):.2f} "
              f"max {(max(t) if t else 0):.2f}  "
              f"no_brief {len(nb):>3}  INFEASIBLE {len(inf):>3}  "
              f"UNKNOWN {len(unk):>3}  witness_invalid {len(tv):>3}")
        wg = [r for r in g if r.get("truth_valid") is False
              and r.get("truth_valid_geom")]
        vg = [r for r in g if r.get("valid_geom")]
        ua = [r["unassigned"] for r in g if r.get("unassigned")]
        print(f"          invalid witnesses failing on EXACT TILING ALONE "
              f"{len(wg):>3}; candidates valid but for tiling {len(vg):>3}; "
              f"unassigned cells p50 {(_p(ua, .5) or 0):.0f} "
              f"max {(max(ua) if ua else 0)}")

    print("\n" + "=" * 78)
    print("Paired, on the same (dwelling, exposure, seed) slot")
    mcnemar(rows, "corpus", "cap")
    mcnemar(rows, "cap", "real")
    mcnemar(rows, "corpus", "real")

    print("\n" + "=" * 78)
    print("Survivor rate by room count")
    counts = sorted({r["n"] for r in rows})
    print(f"  {'n':>3} | " + " | ".join(f"{a:>12}" for a in ARMS))
    for n in counts:
        cells = []
        for arm in ARMS:
            g = [r for r in rows if r["n"] == n and r["arm"] == arm]
            cells.append(f"{sum(1 for r in g if r.get('survivor')):>5}/{len(g):<6}")
        print(f"  {n:>3} | " + " | ".join(cells))

    print("\n" + "=" * 78)
    print("The real arm against how articulated the dwelling is")
    for lo, hi in ((1, 4), (5, 6), (7, 9), (10, 99)):
        g = [r for r in rows if r["arm"] == "real" and lo <= r["min_rects"] <= hi]
        c = [r for r in rows if r["arm"] == "cap" and lo <= r["min_rects"] <= hi]
        if not g:
            continue
        print(f"  min_rects {lo}-{hi if hi < 99 else '+'}  n={len(g):>4}   "
              f"real {sum(1 for r in g if r.get('survivor')) / len(g):.3f}   "
              f"cap {(sum(1 for r in c if r.get('survivor')) / len(c)) if c else 0:.3f}")

    print("\n  Read every `real` number under this file's witness caveat: its")
    print("  ground truth is coverage-soft, so an INFEASIBLE there does not")
    print("  prove the solver failed, only that this witness did not survive.")


if __name__ == "__main__":
    seeds = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    with gzip.open(SERIES, "rt", encoding="utf-8") as fh:
        series = json.load(fh)
    print(f"real arm: {len(series)} dwellings x {len(EXPOSURES)} exposures x "
          f"{seeds} seeds x {len(ARMS)} arms = "
          f"{len(series) * len(EXPOSURES) * seeds * len(ARMS)} solves, "
          f"{SHIPPED_LIMIT} s each at worst\n")
    report(run(series, seeds))
